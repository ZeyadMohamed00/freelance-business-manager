from fpdf import FPDF


def total(items):
    return round(sum(float(i["qty"]) * float(i["unit_price"]) for i in items), 2)


def render(doc, client_name: str) -> bytes:
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, doc.kind.upper(), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(
        0,
        7,
        f"Number: {doc.number}    Issued: {doc.issued}"
        + (f"    Due: {doc.due}" if doc.due else ""),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.cell(0, 7, f"Client: {client_name}    Status: {doc.status}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 11)
    for w, h in [(95, "Description"), (25, "Qty"), (35, "Unit price"), (35, "Amount")]:
        pdf.cell(w, 8, h, border=1)
    pdf.ln()
    pdf.set_font("Helvetica", "", 11)
    for i in doc.items:
        amt = float(i["qty"]) * float(i["unit_price"])
        pdf.cell(95, 8, str(i["description"])[:45], border=1)
        pdf.cell(25, 8, f"{float(i['qty']):g}", border=1)
        pdf.cell(35, 8, f"{float(i['unit_price']):.2f}", border=1)
        pdf.cell(35, 8, f"{amt:.2f}", border=1)
        pdf.ln()
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(155, 10, "Total", border=1)
    pdf.cell(35, 10, f"{total(doc.items):.2f}", border=1)
    pdf.ln(14)
    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(0, 6, "Sample document generated by the Freelance Business Manager demo.")
    return bytes(pdf.output())
